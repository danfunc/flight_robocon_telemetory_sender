#ifndef FLIGHT_ROBOCON_FW_VERSION_HPP
#define FLIGHT_ROBOCON_FW_VERSION_HPP
#include <cstdint>

// ===========================================================================
//  fw_version — 今走っている像そのものの素性 (大きさと CRC32)
// ===========================================================================
//  ★何のためにあるか: **焼けたかどうかを、焼いた側の申告ではなく板に訊く**ため。
//    OTA を流したあと「本当に入れ替わったのか」を確かめる手段が要る。
//    ファイル名やビルド時刻ではなく、板の上の像を実際に読んで出す。
//
//  ★計算は 1 度きりで、あとは控えを返す。像は 400KB 規模あり、なめるのに
//    ミリ秒単位かかる。周期スレッドから毎回呼ばれても困らないようにしておく
//    (呼ぶ側の行儀に賭けない)。
//  ★初回の 1 回は時間を食うので、**時間に厳しい経路で最初に呼ばない**こと。
//    ここでは telemetry の poll が回り始めた最初の 1 回で払っている。
namespace xno {

struct fw_id {
  uint32_t bytes; // 像の大きさ
  uint32_t crc32; // 像全体の CRC32 (反転済み・標準多項式)
};

const fw_id &firmware_id();

} // namespace xno
#endif // FLIGHT_ROBOCON_FW_VERSION_HPP
