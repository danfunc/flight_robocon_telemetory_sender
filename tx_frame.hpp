#ifndef FLIGHT_ROBOCON_TX_FRAME_HPP
#define FLIGHT_ROBOCON_TX_FRAME_HPP
#include <cstdint>

// ===========================================================================
//  オブジェクト間ストリームが運ぶ 1 レコード
// ===========================================================================
//  ★どのオブジェクトにも属さない中立の型としてここに置く。センサ
//    (bno055 / bme280) → flight_controller → ble_uart という経路の全リンクが
//    同じレコードを運ぶので、途中の誰かのヘッダ (例えば ble_uart.hpp) に置くと、
//    センサが BLE を知っていることになってしまう。ハブ化 (D46) でせっかく
//    切った依存を型で繋ぎ直さないための分離。
//
//  ★244B の由来は BLE 側の制約 (ATT MTU 247 - ATT ヘッダ 3。btstack_config.h の
//    HCI_ACL_PAYLOAD_SIZE=(247+4) と同じ話)。トランスポートの都合がレコード長を
//    決めている以上、値の根拠はここに書き残しておく — ただし型そのものは
//    トランスポート非依存に保つ (別の出口が増えてもこの型は変えない)。
//    これを超える長さは**送り手が切る** (分割送信はしない)。
namespace xno {

struct tx_frame {
  uint16_t len;
  uint8_t data[244];
};

// ★「まだ配線されていない」を表す番号。**0 は使えない** — Shizuku の
//   STREAM_CREATE は `m_streams[]` の空きインデックスをそのまま返すので、
//   最初に作られたストリームの番号は 0 であり、0 は完全に正当な番号。
//   実際これで踏んだ (2026-08-24): ble_uart が最初に RX ストリームを作る →
//   番号 0 → 受け取った側が `if (id != 0)` で「未配線」と誤判定し、
//   RX コマンドが**無音でハブに届かない**状態になった (センサ側は番号 1 以降
//   だったので動いており、切り分けが遅れた)。
constexpr uintptr_t NO_STREAM = (uintptr_t)-1;

} // namespace xno
#endif // FLIGHT_ROBOCON_TX_FRAME_HPP
